import OpenAI from "openai";
import {
  connectToMcpServer,
  discoverTools,
  disconnectFromMcpServer,
} from "../mcpClient/mcpClient.js";
import { executeToolTest } from "../toolTestService.js";

const openai = new OpenAI({
  apiKey: process.env.OPENAI_API_KEY,
});

const MODEL = process.env.OPENAI_MODEL || "gpt-6-luna";

/**
 * Convert an MCP tool definition into an OpenAI function tool.
 */
function convertMcpToolToOpenAI(mcpTool) {
  return {
    type: "function",
    name: mcpTool.name,
    description: mcpTool.description || `Execute the MCP tool ${mcpTool.name}.`,
    parameters: mcpTool.inputSchema || {
      type: "object",
      properties: {},
      additionalProperties: false,
    },
  };
}

/**
 * Safely normalize tool execution result.
 */
function normalizeToolResult(result) {
  if (!result) {
    return {
      success: false,
      output: null,
      error: "Tool returned no result.",
      durationMs: 0,
    };
  }

  return {
    success: Boolean(result.success),
    output: result.output ?? null,
    error: result.error ?? null,
    durationMs: Number(result.durationMs || 0),
  };
}

/**
 * Run the AI agent against the MCP server.
 *
 * Flow:
 * 1. Connect to MCP server
 * 2. Dynamically discover MCP tools
 * 3. Give discovered tools to OpenAI
 * 4. Let the model decide which tool to call
 * 5. Execute the selected MCP tool
 * 6. Send tool result back to OpenAI
 * 7. Return final natural-language answer + safe execution trace
 */
export async function runAgent({ message, serverConfig = {} }) {
  if (!message || !message.trim()) {
    throw new Error("Agent message is required.");
  }

  if (!process.env.OPENAI_API_KEY) {
    throw new Error("OPENAI_API_KEY is not configured.");
  }

  let connected = false;

  const executionTrace = [];

  try {
    // ---------------------------------------------------------
    // 1. CONNECT TO MCP SERVER
    // ---------------------------------------------------------

    const connectionConfig = {
      ...serverConfig,
    };

    await connectToMcpServer(connectionConfig);

    connected = true;

    // ---------------------------------------------------------
    // 2. DISCOVER MCP TOOLS DYNAMICALLY
    // ---------------------------------------------------------

    const discoveredTools = await discoverTools();

    if (!Array.isArray(discoveredTools) || discoveredTools.length === 0) {
      throw new Error("No MCP tools were discovered.");
    }

    // ---------------------------------------------------------
    // 3. CONVERT MCP TOOLS INTO OPENAI TOOLS
    // ---------------------------------------------------------

    const openAITools = discoveredTools.map(convertMcpToolToOpenAI);

    // ---------------------------------------------------------
    // 4. INITIAL AGENT REQUEST
    // ---------------------------------------------------------

    let response = await openai.responses.create({
      model: MODEL,

      instructions: `
You are the AI Agent inside MCP Tool Testing Studio.

Your job is to help users interact with MCP tools.

Rules:

1. Use MCP tools when they are appropriate for answering the user's request.
2. Never invent tool results.
3. Use the exact input schema provided by the MCP tool.
4. If required information is missing, ask the user for it.
5. After a tool executes, explain the result clearly.
6. Do not expose hidden chain-of-thought or internal reasoning.
7. You may provide a short technical execution summary such as:
   - tool selected
   - parameters used
   - execution status
   - execution duration
8. If no MCP tool is appropriate, answer normally.
9. Do not claim a tool was executed unless it actually executed successfully.
`,

      input: message,

      tools: openAITools,

      tool_choice: "auto",
    });

    // ---------------------------------------------------------
    // 5. PROCESS TOOL CALLS
    // ---------------------------------------------------------

    let toolCallsExecuted = 0;

    while (true) {
      const toolCalls = response.output.filter(
        (item) => item.type === "function_call",
      );

      if (toolCalls.length === 0) {
        break;
      }

      const toolOutputs = [];

      for (const toolCall of toolCalls) {
        const toolName = toolCall.name;

        let toolArguments = {};

        try {
          toolArguments = toolCall.arguments
            ? JSON.parse(toolCall.arguments)
            : {};
        } catch (error) {
          const traceEntry = {
            toolName,
            arguments: toolCall.arguments,
            status: "FAILED",
            error: "Invalid tool arguments generated by the model.",
            durationMs: 0,
          };

          executionTrace.push(traceEntry);

          toolOutputs.push({
            type: "function_call_output",
            call_id: toolCall.call_id,
            output: JSON.stringify({
              success: false,
              error: "Invalid tool arguments.",
            }),
          });

          continue;
        }

        // -----------------------------------------------------
        // EXECUTE ACTUAL MCP TOOL
        // -----------------------------------------------------

        const startedAt = Date.now();

        let toolResult;

        try {
          toolResult = await executeToolTest(toolName, toolArguments);
        } catch (error) {
          toolResult = {
            success: false,
            output: null,
            error: error.message,
            durationMs: Date.now() - startedAt,
          };
        }

        const normalizedResult = normalizeToolResult(toolResult);

        const durationMs =
          normalizedResult.durationMs || Date.now() - startedAt;

        // -----------------------------------------------------
        // SAFE EXECUTION TRACE
        // -----------------------------------------------------

        executionTrace.push({
          toolName,
          arguments: toolArguments,
          status: normalizedResult.success ? "SUCCESS" : "FAILED",
          durationMs,
          error: normalizedResult.error,
        });

        toolCallsExecuted++;

        // -----------------------------------------------------
        // SEND TOOL RESULT BACK TO MODEL
        // -----------------------------------------------------

        toolOutputs.push({
          type: "function_call_output",
          call_id: toolCall.call_id,
          output: JSON.stringify({
            success: normalizedResult.success,
            output: normalizedResult.output,
            error: normalizedResult.error,
            durationMs,
          }),
        });
      }

      // -------------------------------------------------------
      // 6. CONTINUE THE RESPONSE WITH TOOL RESULTS
      // -------------------------------------------------------

      response = await openai.responses.create({
        model: MODEL,

        instructions: `
You are completing an MCP tool interaction.

Use the tool results provided to answer the user.

Rules:
- Do not invent information.
- Clearly state the actual result.
- If execution failed, explain the failure.
- Do not expose hidden chain-of-thought.
- A concise technical summary is allowed.
`,

        previous_response_id: response.id,

        input: toolOutputs,

        tools: openAITools,

        tool_choice: "auto",
      });
    }

    // ---------------------------------------------------------
    // 7. FINAL RESPONSE
    // ---------------------------------------------------------

    return {
      success: true,

      message: response.output_text || "The agent completed the request.",

      model: MODEL,

      discoveredTools: discoveredTools.map((tool) => ({
        name: tool.name,
        description: tool.description || "",
        inputSchema: tool.inputSchema || {},
      })),

      toolCallsExecuted,

      executionTrace,
    };
  } finally {
    // ---------------------------------------------------------
    // 8. DISCONNECT MCP SERVER
    // ---------------------------------------------------------

    if (connected) {
      try {
        await disconnectFromMcpServer();
      } catch (error) {
        console.error("MCP disconnect warning:", error.message);
      }
    }
  }
}
